"""Emit `chesscoach.separation.DOES_NOT_SEPARATE` from the within-band screen.

Note: docs/notes/experiments.e84-band-references.md

The register is **evidence, not opinion**, so it is generated rather than typed.
[[experiments.e83-spread-rescreen]] built it from a pool mixing players from 720
to 2006; a pooled null over genuinely different rates inflates dispersion, and
every verdict that moved when the pool was split moved the same way -- separated
to flat, twelve times, with no recoveries.

**Within band is the test that matches the claim.** A peer lookup is keyed on
`(band, speed, claim)`, so "you do this more than your peers" is a statement
about the player's own band. Separation has to hold there or the sentence has
nothing under it.

    python register.py > register.txt
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from rescreen import MIN_PLAYERS, best_within_band, cells, dispersion, totals  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
REFERENCE = REPO / "data/raw/out/peers-e84.json"

# E83's own reading of its power analysis: 1.12-1.25x was called a positive
# finding of flatness, and 1.35x the line past which the screen was blind.
CONCLUSIVE_MDE = 1.35


def crit(df: int) -> float:
    """The dispersion this many players could have rejected at p<0.05."""
    z = 1.6449
    return (1 - 2 / (9 * df) + z * math.sqrt(2 / (9 * df))) ** 3


def main() -> int:
    rows = cells(REFERENCE)
    claims = sorted({k.split("|", 2)[2] for k in rows})

    entries = []
    for claim in claims:
        stratum, phi, tail, n = best_within_band(rows, claim)
        if n < MIN_PLAYERS or phi != phi:
            continue  # unmeasured within band is not a verdict
        if tail < 0.05:
            continue  # separates
        obs = totals(rows, claim, stratum)
        p, _, _ = dispersion(obs)
        nbar = sum(x for _, x in obs) / len(obs)
        rho = max(0.0, (crit(len(obs) - 1) - 1) / (nbar - 1))
        mde = (p + math.sqrt(rho * p * (1 - p))) / p
        entries.append((claim, phi, tail, mde, n, stratum, mde <= CONCLUSIVE_MDE))

    print("# Generated by experiments/e84-band-references/register.py")
    print("# Screened within band on peers-e84: three bands, two speeds, denominator A.")
    print("DOES_NOT_SEPARATE: dict[str, Separation] = {")
    for claim, phi, tail, mde, n, stratum, conclusive in sorted(entries, key=lambda r: r[3]):
        print(f'    "{claim}": Separation('
              f"{phi:.2f}, {tail:.3g}, {mde:.2f}, {n}, conclusive={conclusive}),"
              f"  # {stratum}")
    print("}")
    print(f"\n# {len(entries)} claims; "
          f"{sum(1 for e in entries if e[6])} conclusive, "
          f"{sum(1 for e in entries if not e[6])} inconclusive", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
